/**
 * Shared SEO helpers: canonical URLs, social metadata and schema.org JSON-LD.
 *
 * Everything here is server-side only (it reads env and formats absolute URLs),
 * so pages can build consistent metadata without repeating boilerplate.
 */
import type { Metadata } from "next";
import { env } from "./env";
import type { GameRow } from "./games";
import type { Locale } from "./i18n/dictionary";

export const SITE_NAME = "Playnix";
export const SITE_TAGLINE = "Play instantly inside Telegram";
export const SITE_DESCRIPTION =
  "Search thousands of licensed games and play compatible titles instantly inside Telegram. No installs, no APKs.";

/** Languages the site can render, exposed to crawlers via hreflang. */
export const SEO_LOCALES: Locale[] = ["en", "ar", "fr"];
const OG_LOCALES: Record<Locale, string> = { en: "en_US", ar: "ar_AR", fr: "fr_FR" };

/** Default share image (1200×630) generated by scripts/og-image.mjs. */
export const DEFAULT_OG_IMAGE = "/brand/og-1200x630.png";

/** Absolute URL for a site path. `path` may be relative ("/game/x") or absolute. */
export function absoluteUrl(path = "/"): string {
  if (/^https?:\/\//i.test(path)) return path;
  const base = env.siteUrl;
  return `${base}${path.startsWith("/") ? path : `/${path}`}`;
}

/** Absolute URL for a media path; leaves remote URLs untouched. */
export function absoluteMediaUrl(url: string | null | undefined, fallback = DEFAULT_OG_IMAGE): string {
  if (!url) return absoluteUrl(fallback);
  if (/^https?:\/\//i.test(url)) return url;
  return absoluteUrl(url);
}

/** Trim long copy to a tidy meta description (Google shows ~155 chars). */
export function metaDescription(input: string | null | undefined, fallback = SITE_DESCRIPTION, max = 158): string {
  const text = (input ?? "").replace(/\s+/g, " ").trim();
  if (!text) return fallback;
  if (text.length <= max) return text;
  const cut = text.slice(0, max - 1);
  const lastSpace = cut.lastIndexOf(" ");
  return `${(lastSpace > 60 ? cut.slice(0, lastSpace) : cut).trimEnd()}…`;
}

/** Title-case helper for slugs when no human title exists. */
export function humaniseSlug(slug: string): string {
  return slug
    .split(/[-_]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

type BuildMetadataInput = {
  title: string;
  description?: string | null;
  /** Site-relative path of the canonical page, e.g. `/game/neon-serpent`. */
  path: string;
  image?: string | null;
  type?: "website" | "article";
  locale?: Locale;
  keywords?: string[];
  noIndex?: boolean;
  publishedTime?: string | null;
  modifiedTime?: string | null;
};

/**
 * Builds the full metadata block for a page: canonical URL, hreflang
 * alternates, Open Graph, Twitter/X card and robots directives.
 */
export function buildMetadata({
  title,
  description,
  path,
  image,
  type = "website",
  locale = "en",
  keywords,
  noIndex = false,
  publishedTime,
  modifiedTime,
}: BuildMetadataInput): Metadata {
  const resolvedDescription = metaDescription(description);
  const canonical = absoluteUrl(path);
  const imageUrl = absoluteMediaUrl(image);
  const languages = Object.fromEntries(SEO_LOCALES.map((code) => [code, absoluteUrl(path)])) as Record<string, string>;

  return {
    title,
    description: resolvedDescription,
    keywords: keywords?.length ? keywords : undefined,
    alternates: { canonical, languages },
    robots: noIndex
      ? { index: false, follow: true }
      : {
          index: true,
          follow: true,
          googleBot: {
            index: true,
            follow: true,
            "max-image-preview": "large",
            "max-snippet": -1,
            "max-video-preview": -1,
          },
        },
    openGraph: {
      type,
      siteName: SITE_NAME,
      title,
      description: resolvedDescription,
      url: canonical,
      locale: OG_LOCALES[locale] ?? "en_US",
      images: [{ url: imageUrl, width: 1200, height: 630, alt: title }],
      ...(type === "article"
        ? { publishedTime: publishedTime ?? undefined, modifiedTime: modifiedTime ?? undefined }
        : {}),
    },
    twitter: {
      card: "summary_large_image",
      title,
      description: resolvedDescription,
      images: [imageUrl],
    },
  };
}

/* ------------------------------------------------------------------ JSON-LD */

type JsonLdNode = Record<string, unknown>;

/** Wraps any number of schema.org nodes into an @graph document. */
export function jsonLdGraph(nodes: (JsonLdNode | null | undefined)[]): string {
  const graph = nodes.filter((node): node is JsonLdNode => Boolean(node));
  return JSON.stringify({ "@context": "https://schema.org", "@graph": graph });
}

export function organizationNode(): JsonLdNode {
  return {
    "@type": "Organization",
    "@id": `${env.siteUrl}/#organization`,
    name: SITE_NAME,
    url: env.siteUrl,
    logo: absoluteUrl("/brand/logo-mark-1024.png"),
    description: SITE_DESCRIPTION,
  };
}

/** Site-wide node: the brand entity plus the internal search action. */
export function websiteNode(): JsonLdNode {
  return {
    "@type": "WebSite",
    "@id": `${env.siteUrl}/#website`,
    name: SITE_NAME,
    alternateName: "Playnix Games",
    url: env.siteUrl,
    description: SITE_DESCRIPTION,
    inLanguage: SEO_LOCALES,
    publisher: { "@id": `${env.siteUrl}/#organization` },
    potentialAction: {
      "@type": "SearchAction",
      target: { "@type": "EntryPoint", urlTemplate: `${env.siteUrl}/search?q={search_term_string}` },
      "query-input": "required name=search_term_string",
    },
  };
}

export function breadcrumbNode(items: { name: string; path: string }[]): JsonLdNode {
  return {
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: item.name,
      item: absoluteUrl(item.path),
    })),
  };
}

export function itemListNode(name: string, path: string, items: { name: string; path: string }[]): JsonLdNode {
  return {
    "@type": "ItemList",
    name,
    url: absoluteUrl(path),
    numberOfItems: items.length,
    itemListElement: items.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      url: absoluteUrl(item.path),
      name: item.name,
    })),
  };
}

/**
 * Rich result for a game page: the playable `VideoGame` plus an
 * `AggregateRating` when players have rated it.
 */
export function videoGameNode(game: GameRow, ratingCount: number, ratingAvg: number): JsonLdNode {
  const url = absoluteUrl(`/game/${game.slug}`);
  const isPlayable = game.game_type === "html5" && Boolean(game.game_url);
  return {
    "@type": "VideoGame",
    "@id": `${url}#videogame`,
    name: game.title,
    url,
    description: metaDescription(game.description ?? game.short_description, `${game.title} on Playnix.`, 300),
    image: absoluteMediaUrl(game.cover_url),
    inLanguage: SEO_LOCALES,
    ...(game.category_name ? { genre: game.category_name } : {}),
    ...(game.developer ? { author: { "@type": "Organization", name: game.developer } } : {}),
    ...(game.publisher ? { publisher: { "@type": "Organization", name: game.publisher } } : {}),
    ...(game.released_at ? { datePublished: game.released_at } : {}),
    ...(game.supported_devices ? { gamePlatform: game.supported_devices } : {}),
    ...(game.controls ? { playMode: game.controls } : {}),
    applicationCategory: "Game",
    operatingSystem: game.supported_devices || "Any",
    offers: {
      "@type": "Offer",
      price: "0",
      priceCurrency: "USD",
      availability: "https://schema.org/InStock",
      url,
    },
    ...(ratingCount > 0
      ? {
          aggregateRating: {
            "@type": "AggregateRating",
            ratingValue: Number(ratingAvg.toFixed(2)),
            ratingCount,
            bestRating: 5,
            worstRating: 1,
          },
        }
      : {}),
    ...(isPlayable ? { isAccessibleForFree: game.pricing_type === "free" } : {}),
  };
}
